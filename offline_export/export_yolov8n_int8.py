#!/usr/bin/env python3
"""
Team 43 / DVCon India 2026 Stage 3B -- Milestone C export.

Offline conversion of YOLOv8n into an INT8 package the board can execute.
Nothing here depends on a runtime input image: it folds BatchNorm, quantizes
constant weights, pre-packs them into accelerator 8x8 tile order, and emits a
flat op list. Exactly the same class of offline work as the MiniLM export.

Outputs (next to this script):
    team43_yolo_int8.bin      pre-packed INT8 weights + FP32 scales/biases
    team43_yolo_graph.h       op list + per-weight metadata as C constants
    team43_yolo_golden.json   INT8 detections for the two test images
    bus.ppm / zidane.ppm      test images as raw P6 (the board has no JPEG
                              decoder; converting the container is not inference
                              -- the board still does letterbox, normalise,
                              detect, NMS and scoring itself)

WHAT IS LEGAL HERE: BN folding, weight quantization, tile pre-packing, static
metadata, golden references, image container conversion.
WHAT IS NOT DONE HERE: no detection, no activations, no scores for any image.
"""
import json, os, sys
import numpy as np, torch, warnings
warnings.filterwarnings('ignore')
from ultralytics import YOLO
from yolo_flatten import flatten, run_numpy, decode
from yolo_int8_eval import run_int8, detections, letterbox, q_w

HERE = os.path.dirname(os.path.abspath(__file__))
PT   = '/mnt/user-data/uploads/minilm-new-pipeline/yolov8n.pt'
TILE = 8

OPS = {'CONV': 0, 'MAXPOOL': 1, 'UPSAMPLE': 2, 'CONCAT': 3, 'SLICE': 4, 'ADD': 5}
MAXIN = 8

def pack_w(wq, K, N):
    """[N,K] int8 -> accelerator tile order, tile (n0,k0), byte kk*8+cc."""
    KT, NT = (K + 7)//8, (N + 7)//8
    out = np.zeros((NT, KT, 64), np.int8)
    for n0 in range(NT):
        for cc in range(8):
            c = n0*8 + cc
            if c >= N: continue
            row = wq[c]
            for k0 in range(KT):
                lim = min(8, K - k0*8)
                out[n0, k0, np.arange(lim)*8 + cc] = row[k0*8: k0*8 + lim]
    return out.reshape(-1)

def main():
    y = YOLO(PT)
    names = [y.model.names[i] for i in range(len(y.model.names))]
    net = y.model.eval().float().fuse()
    g = flatten(net)

    blob = bytearray()
    wmeta = []
    for wi, (w, b) in enumerate(g.weights):
        N, K = w.shape
        wq, sw = q_w(w)                       # per-output-channel scales
        packed = pack_w(wq.astype(np.int8), K, N)
        off_w = len(blob); blob += packed.tobytes()
        off_s = len(blob); blob += np.pad(sw, (0, (-N) % 8)).astype(np.float32).tobytes()
        off_b = len(blob); blob += np.pad(b,  (0, (-N) % 8)).astype(np.float32).tobytes()
        wmeta.append(dict(k=int(K), n=int(N), off_w=off_w, off_s=off_s, off_b=off_b,
                          bytes=int(packed.size)))

    # tensor last-use, so the board can free buffers as it goes
    lastuse = [-1] * g.n_tensors
    for oi, op in enumerate(g.ops):
        for t in op['i']: lastuse[t] = oi
    for lvl, (bi, ci) in enumerate(g.detect['heads']):
        lastuse[bi] = len(g.ops); lastuse[ci] = len(g.ops)

    det = g.detect
    L = []
    A = L.append
    A('/* auto-generated by export_yolov8n_int8.py - do not edit */')
    A('#ifndef TEAM43_YOLO_GRAPH_H')
    A('#define TEAM43_YOLO_GRAPH_H')
    A('')
    A(f'#define YOLO_NOPS      {len(g.ops)}')
    A(f'#define YOLO_NTENSORS  {g.n_tensors}')
    A(f'#define YOLO_NWEIGHTS  {len(g.weights)}')
    A(f'#define YOLO_NCLASSES  {det["nc"]}')
    A(f'#define YOLO_REG_MAX   {det["reg_max"]}')
    A(f'#define YOLO_NLEVELS   {len(det["strides"])}')
    A(f'#define YOLO_BLOB_BYTES {len(blob)}L')
    A(f'#define YOLO_MAX_IN    {MAXIN}')
    A('')
    A('#define YOP_CONV 0\n#define YOP_MAXPOOL 1\n#define YOP_UPSAMPLE 2')
    A('#define YOP_CONCAT 3\n#define YOP_SLICE 4\n#define YOP_ADD 5')
    A('')
    def arr(name, vals, t='short'):
        A(f'static const {t} {name}[] = {{')
        for i in range(0, len(vals), 20):
            A('    ' + ', '.join(str(v) for v in vals[i:i+20]) + ',')
        A('};')
    arr('YOP_TYPE', [OPS[o['type']] for o in g.ops])
    arr('YOP_OUT',  [o['o'] for o in g.ops])
    arr('YOP_NIN',  [len(o['i']) for o in g.ops])
    A(f'static const short YOP_IN[][{MAXIN}] = {{')
    for o in g.ops:
        ins = list(o['i']) + [-1] * (MAXIN - len(o['i']))
        A('    {' + ', '.join(str(v) for v in ins) + '},')
    A('};')
    arr('YOP_W',   [o.get('w', -1) for o in g.ops])
    arr('YOP_K',   [o.get('k', 0) for o in g.ops])
    arr('YOP_S',   [o.get('s', 0) for o in g.ops])
    arr('YOP_P',   [o.get('p', 0) for o in g.ops])
    arr('YOP_ACT', [1 if o.get('act') == 'silu' else 0 for o in g.ops])
    arr('YOP_C0',  [o.get('c0', 0) for o in g.ops])
    arr('YOP_C1',  [o.get('c1', 0) for o in g.ops])
    arr('YTENSOR_LASTUSE', lastuse)
    arr('YW_K', [m['k'] for m in wmeta])
    arr('YW_N', [m['n'] for m in wmeta])
    arr('YW_OFF',   [m['off_w'] for m in wmeta], 'long')
    arr('YW_SOFF',  [m['off_s'] for m in wmeta], 'long')
    arr('YW_BOFF',  [m['off_b'] for m in wmeta], 'long')
    arr('YDET_BOX', [h[0] for h in det['heads']])
    arr('YDET_CLS', [h[1] for h in det['heads']])
    A('static const float YDET_STRIDE[] = { ' +
      ', '.join(f'{s:.1f}f' for s in det['strides']) + ' };')
    A('static const char *YOLO_NAMES[YOLO_NCLASSES] = {')
    for i in range(0, len(names), 6):
        A('    ' + ', '.join(f'"{n}"' for n in names[i:i+6]) + ',')
    A('};')
    A('')
    A('#endif /* TEAM43_YOLO_GRAPH_H */')

    open(os.path.join(HERE, 'team43_yolo_graph.h'), 'w').write('\n'.join(L) + '\n')
    open(os.path.join(HERE, 'team43_yolo_int8.bin'), 'wb').write(bytes(blob))

    # ---- test images as raw P6, plus INT8 goldens ------------------------
    import ultralytics
    assets = os.path.join(os.path.dirname(ultralytics.__file__), 'assets')
    from PIL import Image
    golden = {}
    for nm in ('bus', 'zidane'):
        src = os.path.join(assets, nm + '.jpg')
        im = Image.open(src).convert('RGB')
        with open(os.path.join(HERE, nm + '.ppm'), 'wb') as f:
            f.write(b'P6\n%d %d\n255\n' % im.size)
            f.write(np.asarray(im, np.uint8).tobytes())
        golden[nm] = {}
        for sz in (128, 192, 256):
            img, _, _ = letterbox(src, sz)
            T = run_int8(g, img)
            dets = detections(g, T, {i: n for i, n in enumerate(names)})
            golden[nm][str(sz)] = [
                dict(cls=n, conf=round(float(s), 6),
                     box=[round(float(v), 2) for v in bx]) for n, s, bx in dets]
            print(f'  {nm} @{sz}: ' + (', '.join(f'{d["cls"]} {d["conf"]:.3f}'
                                                 for d in golden[nm][str(sz)][:6]) or 'nothing'))

    total_inv = {}
    for sz in (128, 192, 256):
        n = 0
        H = {0: (3, sz, sz)}
        for op in g.ops:
            if op['type'] == 'CONV':
                c, h, w = H[op['i'][0]]
                ho = (h + 2*op['p'] - op['k'])//op['s'] + 1
                wo = (w + 2*op['p'] - op['k'])//op['s'] + 1
                K, N = g.weights[op['w']][0].shape[1], g.weights[op['w']][0].shape[0]
                n += ((ho*wo + 7)//8) * ((K + 7)//8) * ((N + 7)//8)
                H[op['o']] = (N, ho, wo)
            elif op['type'] == 'MAXPOOL': H[op['o']] = H[op['i'][0]]
            elif op['type'] == 'UPSAMPLE':
                c, h, w = H[op['i'][0]]; H[op['o']] = (c, h*2, w*2)
            elif op['type'] == 'CONCAT':
                hs = [H[j] for j in op['i']]
                H[op['o']] = (sum(t[0] for t in hs), hs[0][1], hs[0][2])
            elif op['type'] == 'SLICE':
                c, h, w = H[op['i'][0]]; H[op['o']] = (op['c1']-op['c0'], h, w)
            elif op['type'] == 'ADD': H[op['o']] = H[op['i'][0]]
        total_inv[sz] = n

    json.dump(dict(model='yolov8n', source=PT, quantization=
                   'per-output-channel symmetric int8 weights, per-tensor int8 '
                   'activations, INT32 accumulate',
                   bn='folded', blob_bytes=len(blob), n_ops=len(g.ops),
                   n_weights=len(g.weights), invocations=total_inv,
                   detections=golden),
              open(os.path.join(HERE, 'team43_yolo_golden.json'), 'w'), indent=2)

    print(f'\nwrote team43_yolo_int8.bin   {len(blob):,} bytes')
    print(f'wrote team43_yolo_graph.h    {len(g.ops)} ops, {len(g.weights)} weights')
    print('invocations:', ', '.join(f'{k}px={v:,}' for k, v in total_inv.items()))

if __name__ == '__main__':
    main()
