#!/usr/bin/env python3
"""
Reads team43_minilm_manifest.json and emits team43_minilm_layout.h so the
board C program can index the 23 MB weight blob with compile-time constants.
No JSON parsing on the board. The .bin file is NOT modified or re-exported.

    python make_layout_header.py
"""
import json, re
from pathlib import Path

HERE = Path(__file__).resolve().parent
man = json.loads((HERE / "team43_minilm_manifest.json").read_text())

def cfloat(v):
    """Emit a VALID C float literal.

    The previous version wrote f"{v:.12g}f", which turns a scale of exactly
    1.0 into the token `1f`. That is legal C#, not legal C -- gcc rejects it
    with "invalid suffix 'f' on integer constant", so every FP32 side table
    in the generated header (all LayerNorm params and all biases, SCALE = 1.0)
    made the header uncompilable. Force a decimal point.
    """
    s = f"{v:.12g}"
    if ("." not in s) and ("e" not in s) and ("E" not in s):
        s += ".0"
    return s + "f"


def cname(n):
    return "T_" + re.sub(r"[^0-9A-Za-z]", "_", n).upper()

lines = [
    "/* auto-generated by make_layout_header.py - do not edit */",
    "#ifndef TEAM43_MINILM_LAYOUT_H",
    "#define TEAM43_MINILM_LAYOUT_H",
    "",
    f'#define MINILM_HIDDEN      {man["hidden"]}',
    f'#define MINILM_LAYERS      {man["layers"]}',
    f'#define MINILM_HEADS       {man["heads"]}',
    f'#define MINILM_FFN         {man["ffn"]}',
    f'#define MINILM_MAX_TOKENS  {man["max_tokens"]}',
    f'#define MINILM_VOCAB       {man["vocab_size"]}',
    f'#define MINILM_BLOB_BYTES  {man["package_bytes"]}L',
    f'#define MINILM_NCLASSES    {len(man["coco_classes"])}',
    "",
]

for t in man["tensors"]:
    b = cname(t["name"])
    shape = t["shape"] + [1, 1]
    lines += [
        f'#define {b}_OFF   {t["offset"]}L',
        f'#define {b}_D0    {shape[0]}',
        f'#define {b}_D1    {shape[1]}',
        f'#define {b}_SCALE {cfloat(t["scale"])}',
        f'#define {b}_IS_I8 {1 if t["dtype"] == "int8" else 0}',
        "",
    ]

names = ", ".join(f'"{c}"' for c in man["coco_classes"])
lines += [
    "static const char *COCO_NAMES[MINILM_NCLASSES] = {",
    "    " + names,
    "};",
    "",
    "#endif /* TEAM43_MINILM_LAYOUT_H */",
]

out = HERE / "team43_minilm_layout.h"
out.write_text("\n".join(lines))
print(f"wrote {out}  ({len(lines)} lines, {len(man['tensors'])} tensors)")
print("tensor names available as macros:")
for t in man["tensors"][:6]:
    print(f"   {cname(t['name'])}_OFF  shape={t['shape']}  scale={t['scale']:.3e}")
print("   ...")
