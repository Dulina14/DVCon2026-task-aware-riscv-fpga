static long elapsed_us(const struct timeval *start, const struct timeval *end)
{
    return (end->tv_sec - start->tv_sec) * 1000000L
         + (end->tv_usec - start->tv_usec);
}

static int write_word(int fd, uint32_t value, off_t offset)
{
    if (pwrite(fd, &value, 1, offset) < 0) {
        perror("pwrite register");
        return -1;
    }
    return 0;
}

static int read_word(int fd, uint32_t *value, off_t offset)
{
    if (pread(fd, value, 1, offset) < 0) {
        perror("pread register");
        return -1;
    }
    return 0;
}

static void initialise_tensors(int m, int kdim, int n)
{
    int i;
    (void)m;
    (void)kdim;
    (void)n;
    for (i = 0; i < 8 * 32; ++i)
        matrix_x[i] = actual_x[i];
    for (i = 0; i < 32 * 80; ++i)
        matrix_w[i] = actual_w[i];
    for (i = 0; i < 80; ++i)
        bias_vector[i] = actual_bias[i];
    for (i = 0; i < 8 * 80; ++i) {
        matrix_hw[i] = 0;
        matrix_cpu[i] = 0;
    }
}

static long calculate_cpu_golden(int m, int kdim, int n)
{
    int i;
    (void)m;
    (void)kdim;
    (void)n;
    for (i = 0; i < 8 * 80; ++i)
        matrix_cpu[i] = actual_golden[i];
    return 0;
}

static void pack_x_tile(uint32_t words[INPUT_WORDS], int kdim,
                        int tile_row, int tile_k)
{
    int rr, kk;

    for (kk = 0; kk < (int)INPUT_WORDS; ++kk)
        words[kk] = 0;

    /* Accelerator X stream is column-major within an 8x8 tile. */
    for (kk = 0; kk < TILE; ++kk) {
        for (rr = 0; rr < TILE; ++rr) {
            unsigned int index = (unsigned int)(kk * TILE + rr);
            unsigned int word = index / 4u;
            unsigned int lane = index % 4u;
            int global_r = tile_row * TILE + rr;
            int global_k = tile_k * TILE + kk;
            uint32_t byte_value =
                (uint32_t)(uint8_t)matrix_x[global_r * kdim + global_k];
            words[word] |= byte_value << (lane * 8u);
        }
    }
}

static void pack_w_tile(uint32_t words[INPUT_WORDS], int n,
                        int tile_k, int tile_col)
{
    int kk, cc;

    for (kk = 0; kk < (int)INPUT_WORDS; ++kk)
        words[kk] = 0;

    /* Accelerator weight stream is row-major within an 8x8 tile. */
    for (kk = 0; kk < TILE; ++kk) {
        for (cc = 0; cc < TILE; ++cc) {
            unsigned int index = (unsigned int)(kk * TILE + cc);
            unsigned int word = index / 4u;
            unsigned int lane = index % 4u;
            int global_k = tile_k * TILE + kk;
            int global_c = tile_col * TILE + cc;
            uint32_t byte_value =
                (uint32_t)(uint8_t)matrix_w[global_k * n + global_c];
            words[word] |= byte_value << (lane * 8u);
        }
    }
}

static int run_physical_tile(int fd,
                             const uint32_t w_words[INPUT_WORDS],
                             const uint32_t x_words[INPUT_WORDS],
                             int32_t partial[OUTPUT_WORDS],
                             long *command_done_us)
{
    uint32_t status = 0;
    unsigned int guard;
    struct timeval start, end;

    if (write_word(fd, 0u, REG_START) < 0)
        return -1;

    if (pwrite(fd, w_words, INPUT_WORDS, K_ADDR) < 0 ||
        pwrite(fd, x_words, INPUT_WORDS, X_ADDR) < 0 ||
        pwrite(fd, partial, OUTPUT_WORDS, BIAS_ADDR) < 0) {
        perror("pwrite tile operands");
        return -1;
    }

    if (write_word(fd, K_ADDR,       REG_K_ADDR)  < 0 ||
        write_word(fd, INPUT_BYTES,  REG_K_BYTES) < 0 ||
        write_word(fd, 0u,           REG_K_TUSER) < 0 ||
        write_word(fd, X_ADDR,       REG_X_ADDR)  < 0 ||
        write_word(fd, INPUT_BYTES,  REG_X_BYTES) < 0 ||
        write_word(fd, 0u,           REG_X_TUSER) < 0 ||
        write_word(fd, BIAS_ADDR,    REG_B_ADDR)  < 0 ||
        write_word(fd, OUTPUT_BYTES, REG_B_BYTES) < 0 ||
        write_word(fd, 0u,           REG_B_TUSER) < 0 ||
        write_word(fd, Y_ADDR,       REG_Y_ADDR)  < 0 ||
        write_word(fd, OUTPUT_BYTES, REG_Y_BYTES) < 0)
        return -1;

    gettimeofday(&start, NULL);
    if (write_word(fd, 1u, REG_START) < 0)
        return -1;

    for (guard = 0; guard < POLL_LIMIT; ++guard) {
        if (read_word(fd, &status, REG_Y_DONE) < 0)
            return -1;
        if ((status & 1u) != 0u)
            break;
    }
    gettimeofday(&end, NULL);

    if (guard == POLL_LIMIT) {
        printf("Tile timeout: status=0x%08x\n", status);
        write_word(fd, 0u, REG_START);
        return -2;
    }

    *command_done_us += elapsed_us(&start, &end);

    if (pread(fd, partial, OUTPUT_WORDS, Y_ADDR) < 0) {
        perror("pread tile result");
        write_word(fd, 0u, REG_START);
        return -1;
    }

    if (write_word(fd, 0u, REG_START) < 0)
        return -1;

    return 0;
}

static int run_rectangular_test(int fd, const char *label,
                                int m, int kdim, int n)
{
    uint32_t x_words[INPUT_WORDS];
    uint32_t w_words[INPUT_WORDS];
    int32_t partial[OUTPUT_WORDS];
    int row_tiles = m / TILE;
    int k_tiles = kdim / TILE;
    int col_tiles = n / TILE;
    int tile_row, tile_k, tile_col;
    int rr, cc;
    int errors = 0;
    long cpu_us;
    long command_done_us = 0;
    long total_hw_us;
    unsigned int invocations = 0;
    struct timeval hw_start, hw_end;

    if (m <= 0 || kdim <= 0 || n <= 0 ||
        m > MAX_M || kdim > MAX_K || n > MAX_N ||
        (m % TILE) != 0 || (kdim % TILE) != 0 || (n % TILE) != 0) {
        printf("FAIL %s: dimensions must be positive multiples of 8\n", label);
        return 1;
    }

    printf("\n%s\n", label);
    printf("  Logical operation: X[%d,%d] * W[%d,%d] + bias[%d]\n",
           m, kdim, kdim, n, n);

    initialise_tensors(m, kdim, n);
    cpu_us = calculate_cpu_golden(m, kdim, n);

    gettimeofday(&hw_start, NULL);

    for (tile_row = 0; tile_row < row_tiles; ++tile_row) {
        for (tile_col = 0; tile_col < col_tiles; ++tile_col) {
            /* Broadcast one bias value per output channel across rows. */
            for (cc = 0; cc < TILE; ++cc) {
                int global_c = tile_col * TILE + cc;
                for (rr = 0; rr < TILE; ++rr)
                    partial[cc * TILE + rr] = bias_vector[global_c];
            }

            for (tile_k = 0; tile_k < k_tiles; ++tile_k) {
                int rc;

                pack_x_tile(x_words, kdim, tile_row, tile_k);
                pack_w_tile(w_words, n, tile_k, tile_col);

                rc = run_physical_tile(fd, w_words, x_words, partial,
                                       &command_done_us);
                if (rc != 0) {
                    printf("FAIL %s: tile=(%d,%d,%d), rc=%d\n",
                           label, tile_row, tile_col, tile_k, rc);
                    return 1;
                }
                ++invocations;
            }

            for (cc = 0; cc < TILE; ++cc) {
                for (rr = 0; rr < TILE; ++rr) {
                    int global_r = tile_row * TILE + rr;
                    int global_c = tile_col * TILE + cc;
                    matrix_hw[global_r * n + global_c] =
                        partial[cc * TILE + rr];
                }
            }
        }
    }

    gettimeofday(&hw_end, NULL);
    total_hw_us = elapsed_us(&hw_start, &hw_end);

    for (rr = 0; rr < m; ++rr) {
        for (cc = 0; cc < n; ++cc) {
            int index = rr * n + cc;
            if (matrix_hw[index] != matrix_cpu[index]) {
                if (errors < 8) {
                    printf("Mismatch Y[%d][%d]: got %d expected %d\n",
                           rr, cc, matrix_hw[index], matrix_cpu[index]);
                }
                ++errors;
            }
        }
    }

    if (errors != 0) {
        printf("FAIL %s: %d of %d outputs mismatched\n",
               label, errors, m * n);
        return 1;
    }

    printf("  PASS: %d/%d outputs match\n", m * n, m * n);
    printf("  Physical 8x8 invocations   : %u\n", invocations);
    printf("  Sum command-to-DONE time   : %ld us\n", command_done_us);
    printf("  Total hardware-assisted time: %ld us\n", total_hw_us);
    (void)cpu_us;
    printf("  Integer golden reference   : exported from PyTorch\n");
    printf("  Pre-SiLU max/mean error    : %.9f / %.9f\n", ACTUAL_PREACT_MAX_ERROR, ACTUAL_PREACT_MEAN_ERROR);
    printf("  Post-SiLU max/mean error   : %.9f / %.9f\n", ACTUAL_SILU_MAX_ERROR, ACTUAL_SILU_MEAN_ERROR);
    printf("  Samples: Y[0][0]=%d, Y[%d][%d]=%d\n",
           matrix_hw[0], m - 1, n - 1, matrix_hw[m * n - 1]);

    return 0;
}

